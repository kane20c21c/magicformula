from __future__ import annotations
from dataclasses import dataclass


@dataclass(frozen=True)
class BounceConfig:
    version: str = "v1.1.1.1"
    min_drive_days: int = 3          # 연속 하락일 최소
    min_drop: float = -0.20          # 드라이브 누적 낙폭 상한 (이하면 신호)
    strong_sigma: float = 1.65       # 강한 반등 임계 (σ 배수)
    deadcat_sigma: float = 0.30      # 약한 반등 (데드캣) 임계
    sigma_window: int = 60           # σ 창 (거래일)
    min_history: int = 70            # σ 계산에 필요한 최소 행수
    hold_days: int = 5               # 권고 보유일 (연구: 5일 고정 ≈ 저점손절형)
    exclude_sectors: tuple = ("ETF",)


DEFAULT = BounceConfig()
